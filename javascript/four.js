//variable declaration using var
// we can redeclare variables using var key word
var age=21;
var age=35;
console.log(age);

//variable declaration using let
//we cannot redeclare a variable but we can update it.

let name="ramu";
//let name="raju";
name="rahul";
console.log(name);

//variable declaration using const
//we cannot update const variable
//it is fixed
const PI=3.14;
console.log(PI);

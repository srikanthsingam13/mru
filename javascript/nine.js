//unary operators, ++,--
//pre increment operator
let a=5;
console.log(++a);
//5+1=6---display

//post increment
let b=10;
console.log(b++);
//display,10+1
console.log(b);

let c=7;
console.log(++c*c++);


//pre decrement --
let d=5;
console.log(--d);

//post decrement 
let e=10;
console.log(e--);
console.log(e);
